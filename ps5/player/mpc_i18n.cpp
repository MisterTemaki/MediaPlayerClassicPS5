const char* LanguageName(int lang)
{
	return lang >= 0 && lang < int(Language::Count) ? kLanguageNames[lang] : kLanguageNames[0];
}

const char* T(const char* english)
{
	const int lang = AppSettings().language;
	if (lang <= 0 || lang >= int(Language::Count) || !english || !*english)
		return english;
	const auto& index = Index();
	const auto it = index.find(english);
	if (it == index.end())
	{
#ifndef __PROSPERO__
		// the host tests: every text shown without a translation, once (MPCPS5_HOST_I18N_MISSING=<file>)
		if (const char* path = getenv("MPCPS5_HOST_I18N_MISSING"))
		{
			static std::mutex m;
			static std::set<std::string> seen;
			std::lock_guard<std::mutex> lock(m);
			if (seen.insert(english).second)
				if (FILE* f = fopen(path, "a"))
				{
					fprintf(f, "%s\n", english);
					fclose(f);
				}
		}
#endif
		return english;
	}
	const Entry& e = *it->second;
	const char* t = lang == 1 ? e.es : lang == 2 ? e.pt : lang == 3 ? e.fr : e.de;
	return t && *t ? t : english;
}

const char* TC(const char* context, const char* english)
{
	if (AppSettings().language <= 0)
		return english;
	const std::string key = std::string(context) + "|" + english;
	const auto& index = Index();
	const auto it = index.find(key);
	if (it == index.end())
		return T(english);
	return T(it->second->en);
}

std::string Fmt(const char* fmt, ...)
{
	char buf[2048];
	va_list ap;
	va_start(ap, fmt);
	vsnprintf(buf, sizeof(buf), fmt, ap);
	va_end(ap);
	return buf;
}
